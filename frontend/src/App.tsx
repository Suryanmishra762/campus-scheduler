import { useState, useCallback, useMemo } from 'react';
import Sidebar from './components/layout/Sidebar';
import TopBar from './components/layout/TopBar';
import DashboardPage from './pages/DashboardPage';
import TimetablePage from './pages/TimetablePage';
import RoomsPage from './pages/RoomsPage';
import FacultyPage from './pages/FacultyPage';
import ExamsPage from './pages/ExamsPage';
import BookingsPage from './pages/BookingsPage';
import CoordinatorDashboardPage from './pages/coordinator/CoordinatorDashboardPage';
import FacultyPortalPage from './pages/faculty/FacultyPortalPage';
import ClubDashboardPage from './pages/club/ClubDashboardPage';
import { useApi } from './hooks/useApi';
import { fetchFaculty } from './services/api';
import type { PageId, UserRole, CoordinatorPageId, FacultyPageId, ClubPageId, Faculty } from './types';

const pageTitles: Record<PageId, { title: string; subtitle: string }> = {
  // Admin pages
  dashboard: { title: 'Dashboard', subtitle: 'Campus scheduling overview' },
  timetable: { title: 'Timetable', subtitle: 'Weekly class schedule' },
  rooms: { title: 'Rooms & Venues', subtitle: 'Manage campus facilities' },
  faculty: { title: 'Faculty Directory', subtitle: 'Faculty directory & schedules' },
  exams: { title: 'Examinations', subtitle: 'Exam schedule management' },
  bookings: { title: 'Venue Bookings', subtitle: 'Booking requests & approvals' },

  // Department Coordinator pages
  'coordinator-overview': {
    title: 'Department Overview',
    subtitle: 'Department academic metrics, faculty, courses & labs',
  },
  'coordinator-timetable': {
    title: 'Department Timetable',
    subtitle: 'Class schedules and cohort timetable allocations',
  },
  'coordinator-sessions': {
    title: 'Session Change Proposals',
    subtitle: 'Request session reschedules and venue moves',
  },
  'coordinator-bookings': {
    title: 'Department Event Bookings',
    subtitle: 'Reserve venues for departmental seminars, workshops & lectures',
  },
  'coordinator-approvals': {
    title: 'Department Lab Approvals',
    subtitle: 'Review venue requests utilizing departmental laboratories',
  },

  // Faculty Member pages
  'faculty-overview': {
    title: 'Faculty Portal Overview',
    subtitle: 'Personal academic overview and workload tracking',
  },
  'faculty-timetable': {
    title: 'Personal Timetable',
    subtitle: 'Weekly teaching timetable generated by CP-SAT solver',
  },
  'faculty-unavailability': {
    title: 'Mark Unavailability',
    subtitle: 'Submit unavailable periods for solver constraint planning',
  },
  'faculty-sessions': {
    title: 'Session Requests',
    subtitle: 'Request remedial classes, extra practicals or session swaps',
  },
  'faculty-ai': {
    title: 'AI Schedule Assistant',
    subtitle: 'Interactive conversational schedule assistant (UI prototype)',
  },

  // Club Representative pages
  'club-overview': {
    title: 'Club Events Dashboard',
    subtitle: 'Overview of campus club events and venue reservations',
  },
  'club-submit': {
    title: 'Submit Venue Request',
    subtitle: 'Request campus facilities for club activities, workshops & hackathons',
  },
  'club-requests': {
    title: 'My Submitted Requests',
    subtitle: 'Track booking approvals, alternative offers, and solver decision notes',
  },
  'club-tracker': {
    title: 'Venue Status Tracker',
    subtitle: 'Campus facility status and club reservation tracking',
  },
};

function App() {
  const [currentRole, setCurrentRole] = useState<UserRole>('admin');
  const [currentPage, setCurrentPage] = useState<PageId>('dashboard');
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false);
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);
  const [selectedFacultyId, setSelectedFacultyId] = useState('F01');
  const [coordinatorDept, setCoordinatorDept] = useState('CSE');
  const [adminFacultyScheduleId, setAdminFacultyScheduleId] = useState<string | null>(null);

  // Load faculty list for role profile synchronization
  const { data: facultyList } = useApi(fetchFaculty);

  const selectedFaculty: Faculty | undefined = useMemo(() => {
    if (!facultyList || facultyList.length === 0) return undefined;
    return facultyList.find((f) => f.id === selectedFacultyId) ?? facultyList[0];
  }, [facultyList, selectedFacultyId]);

  const handleFacultyChange = useCallback((facultyId: string) => {
    setSelectedFacultyId(facultyId);
  }, []);

  const handleViewFacultySchedule = useCallback((facultyId: string) => {
    setAdminFacultyScheduleId(facultyId);
    setCurrentPage('timetable');
  }, []);

  const handleClearFacultySchedule = useCallback(() => {
    setAdminFacultyScheduleId(null);
  }, []);

  const handleCoordinatorDeptChange = useCallback((dept: string) => {
    setCoordinatorDept(dept);
  }, []);

  const handleNavigate = useCallback((page: string) => {
    setCurrentPage(page as PageId);
    setMobileMenuOpen(false);
  }, []);

  const handleRoleChange = useCallback((newRole: UserRole) => {
    setCurrentRole(newRole);
    if (newRole === 'admin') {
      setCurrentPage('dashboard');
    } else if (newRole === 'coordinator') {
      setCurrentPage('coordinator-overview');
    } else if (newRole === 'faculty') {
      setCurrentPage('faculty-overview');
    } else if (newRole === 'club') {
      setCurrentPage('club-overview');
    }
  }, []);

  const handleToggleCollapse = useCallback(() => {
    if (window.innerWidth < 1024) {
      setMobileMenuOpen(false);
    } else {
      setSidebarCollapsed((prev) => !prev);
    }
  }, []);

  const handleMenuToggle = useCallback(() => {
    setMobileMenuOpen((prev) => !prev);
  }, []);

  const renderPage = () => {
    switch (currentRole) {
      case 'coordinator':
        return (
          <CoordinatorDashboardPage
            activeTab={currentPage as CoordinatorPageId}
            onTabChange={(tab) => handleNavigate(tab)}
            selectedDepartment={coordinatorDept}
            onDepartmentChange={handleCoordinatorDeptChange}
          />
        );
      case 'faculty':
        return (
          <FacultyPortalPage
            activeTab={currentPage as FacultyPageId}
            onTabChange={(tab) => handleNavigate(tab)}
            selectedFacultyId={selectedFacultyId}
            onFacultyChange={handleFacultyChange}
            facultyList={facultyList ?? undefined}
          />
        );
      case 'club':
        return (
          <ClubDashboardPage
            activeTab={currentPage as ClubPageId}
            onTabChange={(tab) => handleNavigate(tab)}
          />
        );
      case 'admin':
      default:
        switch (currentPage) {
          case 'dashboard':
            return <DashboardPage onNavigate={handleNavigate} />;
          case 'timetable':
            return (
              <TimetablePage
                selectedFacultyId={adminFacultyScheduleId}
                onClearFacultyFilter={handleClearFacultySchedule}
                onFacultyChange={(id) => setAdminFacultyScheduleId(id)}
              />
            );
          case 'rooms':
            return <RoomsPage />;
          case 'faculty':
            return <FacultyPage onViewSchedule={handleViewFacultySchedule} />;
          case 'exams':
            return <ExamsPage />;
          case 'bookings':
            return <BookingsPage />;
          default:
            return <DashboardPage onNavigate={handleNavigate} />;
        }
    }
  };

  const pageMeta = pageTitles[currentPage] ?? {
    title: 'CIT Campus Scheduler',
    subtitle: 'Campus Operations',
  };

  return (
    <div className="flex h-screen bg-[#F8F3E7] text-[#1E1E1E] overflow-hidden antialiased">
      {/* Mobile overlay with blur */}
      {mobileMenuOpen && (
        <div
          className="fixed inset-0 bg-black/45 backdrop-blur-xs z-40 lg:hidden"
          onClick={() => setMobileMenuOpen(false)}
        />
      )}

      {/* Floating Dark Sidebar (Desktop: floating rounded pill card; Mobile: slide-in drawer) */}
      <div
        className={`
          fixed lg:static inset-y-0 left-0 z-50
          p-2.5 lg:p-3.5 pr-0
          transform transition-transform duration-300 ease-in-out
          ${mobileMenuOpen ? 'translate-x-0' : '-translate-x-full lg:translate-x-0'}
        `}
      >
        <Sidebar
          currentPage={currentPage}
          onNavigate={handleNavigate}
          collapsed={sidebarCollapsed}
          onToggleCollapse={handleToggleCollapse}
          currentRole={currentRole}
        />
      </div>

      {/* Main content area */}
      <div className="flex-1 flex flex-col min-w-0 h-full overflow-hidden p-2.5 lg:p-3.5 pl-2 lg:pl-3">
        <TopBar
          title={pageMeta.title}
          subtitle={pageMeta.subtitle}
          onMenuToggle={handleMenuToggle}
          currentRole={currentRole}
          onRoleChange={handleRoleChange}
          activeFaculty={selectedFaculty}
          activeCoordinatorDept={currentRole === 'coordinator' ? coordinatorDept : undefined}
          onNavigate={handleNavigate}
        />

        {/* Page content */}
        <main className="flex-1 overflow-y-auto px-1 sm:px-2 pt-1 pb-4">
          {renderPage()}
        </main>
      </div>
    </div>
  );
}

export default App;
